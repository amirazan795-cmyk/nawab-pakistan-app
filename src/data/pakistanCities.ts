// Haversine distance in KM
export function getDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// Find closest Pakistani city to GPS coordinates
export function findNearestPakistanCity(lat: number, lng: number): string {
  let closestCity = 'Rawalpindi';
  let minDistance = Infinity;

  for (const [cityName, coords] of Object.entries(PAKISTAN_GEO_HUBS)) {
    const dist = getDistanceKm(lat, lng, coords.lat, coords.lng);
    if (dist < minDistance) {
      minDistance = dist;
      closestCity = cityName;
    }
  }

  // Format cleaned city name
  return closestCity.replace(/([A-Z])/g, ' $1').trim();
}

// Check if cityB is considered nearby to cityA
export function isNearbyPakistanCity(cityA: string, cityB: string): boolean {
  if (!cityA || !cityB) return false;
  const normA = cityA.toLowerCase().trim();
  const normB = cityB.toLowerCase().trim();

  if (normA === normB) return true;

  // Check cluster entries
  for (const [hub, neighbors] of Object.entries(NEARBY_CLUSTERS)) {
    const hubNorm = hub.toLowerCase();
    const neighborNorms = neighbors.map((n) => n.toLowerCase());

    const inClusterA = normA === hubNorm || neighborNorms.includes(normA);
    const inClusterB = normB === hubNorm || neighborNorms.includes(normB);

    if (inClusterA && inClusterB) {
      return true;
    }
  }

  // Check distance if both are in hubs
  const cleanKeyA = Object.keys(PAKISTAN_GEO_HUBS).find(
    (k) => k.toLowerCase() === normA.replace(/\s+/g, '')
  );
  const cleanKeyB = Object.keys(PAKISTAN_GEO_HUBS).find(
    (k) => k.toLowerCase() === normB.replace(/\s+/g, '')
  );

  if (cleanKeyA && cleanKeyB) {
    const coordsA = PAKISTAN_GEO_HUBS[cleanKeyA];
    const coordsB = PAKISTAN_GEO_HUBS[cleanKeyB];
    const dist = getDistanceKm(coordsA.lat, coordsA.lng, coordsB.lat, coordsB.lng);
    return dist <= 95; // Within 95 km is nearby!
  }

  return false;
}
